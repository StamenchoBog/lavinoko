"""Generate the frontend's data types and runtime check from contract/models.py.

Usage:
    cd backend && uv run python -m contract.generate           # write the files
    cd backend && uv run python -m contract.generate --check   # fail if they are out of date (CI)

Writes:
    frontend/src/lib/contract/types.gen.ts    TypeScript types for every data file
    frontend/src/lib/contract/schema.gen.ts   a compact schema the page checks fetched files against
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from contract.models import ROOTS

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "frontend" / "src" / "lib" / "contract"
HEADER = "// Generated by backend/contract/generate.py from backend/contract/models.py. Do not edit.\n"
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def json_schema() -> tuple[dict[str, str], dict[str, dict]]:
    """Root name -> definition name, and all definitions."""
    refs, schema = models_json_schema([(m, "validation") for m in ROOTS.values()], ref_template="#/$defs/{model}")
    roots = {name: ref_name(refs[(m, "validation")]["$ref"]) for name, m in ROOTS.items()}
    return roots, schema["$defs"]


def ref_name(ref: str) -> str:
    return ref.removeprefix("#/$defs/")


# --- TypeScript ---------------------------------------------------------------------------------


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return ref_name(s["$ref"])
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            return " | ".join(ts_type(x) for x in s[key])
    t = s.get("type")
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts_type(x) for x in s["prefixItems"]) + "]"
        item = ts_type(s["items"])
        return f"({item})[]" if " | " in item else f"{item}[]"
    if t == "object":
        if "properties" in s:
            return "{ " + " ".join(f"{line};" for line in ts_members(s)) + " }"
        extra = s.get("additionalProperties")
        return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    simple = {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}
    if t in simple:
        return simple[t]
    raise ValueError(f"No TypeScript type for schema {s}")


def ts_members(s: dict) -> list[str]:
    required = set(s.get("required", []))
    out = []
    for key, prop in s["properties"].items():
        name = key if IDENT.match(key) else json.dumps(key)
        opt = "" if key in required else "?"
        out.append(f"{name}{opt}: {ts_type(prop)}")
    return out


def doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    lines = text.strip().splitlines()
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {line}".rstrip() + "\n" for line in lines) + f"{indent} */\n"


def typescript(roots: dict[str, str], defs: dict[str, dict]) -> str:
    parts = [HEADER]
    for name in sorted(defs):
        s = defs[name]
        out = doc(s.get("description"))
        if s.get("type") == "object" and "properties" in s:
            required = set(s.get("required", []))
            out += f"export interface {name} {{\n"
            for key, prop in s["properties"].items():
                pname = key if IDENT.match(key) else json.dumps(key)
                opt = "" if key in required else "?"
                out += doc(prop.get("description"), "  ")
                out += f"  {pname}{opt}: {ts_type(prop)};\n"
            out += "}\n"
        else:
            out += f"export type {name} = {ts_type(s)};\n"
        parts.append(out)
    roots_ts = "".join(f"  {k}: {v};\n" for k, v in roots.items())
    parts.append(
        f"/** Each data file the page checks, by its name in the schema. */\nexport interface Roots {{\n{roots_ts}}}\n"
    )
    return "\n".join(parts)


# --- Runtime schema -----------------------------------------------------------------------------

KEEP = {"type", "enum", "const", "$ref", "anyOf", "oneOf", "properties", "required", "items", "prefixItems"}


def compact(s: dict) -> dict:
    """Only what the page's check needs. Unknown fields are allowed on the page (a newer backend may
    add one before the page knows it), so `additionalProperties: false` is left out."""
    out: dict = {}
    for k, v in s.items():
        if k == "$ref":
            out[k] = ref_name(v)
        elif k == "properties":
            out[k] = {pk: compact(pv) for pk, pv in v.items()}
        elif k in ("anyOf", "oneOf", "prefixItems"):
            out[k] = [compact(x) for x in v]
        elif k == "items" or (k == "additionalProperties" and isinstance(v, dict)):
            out[k] = compact(v)
        elif k == "discriminator":
            out[k] = {
                "propertyName": v["propertyName"],
                "mapping": {mk: ref_name(mv) for mk, mv in v["mapping"].items()},
            }
        elif k in KEEP:
            out[k] = v
    return out


def runtime_schema(roots: dict[str, str], defs: dict[str, dict]) -> str:
    body = {"roots": roots, "defs": {name: compact(defs[name]) for name in sorted(defs)}}
    return (
        HEADER
        + "import type { Schema } from './check';\n\n"
        + f"export const SCHEMA: Schema = {json.dumps(body, ensure_ascii=False, indent=2)};\n"
    )


def outputs() -> dict[Path, str]:
    roots, defs = json_schema()
    return {OUT / "types.gen.ts": typescript(roots, defs), OUT / "schema.gen.ts": runtime_schema(roots, defs)}


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the frontend data contract from the backend models.")
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        current = path.read_text() if path.exists() else ""
        if current == text:
            continue
        if args.check:
            stale.append(path)
            diff = difflib.unified_diff(current.splitlines(), text.splitlines(), str(path), "generated", lineterm="")
            print("\n".join(list(diff)[:60]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        names = ", ".join(str(p.relative_to(ROOT)) for p in stale)
        print(f"::error::Data contract out of date: {names}. Run `cd backend && uv run python -m contract.generate`.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
